  function escapeHtml(value) {
    return String(value).replace(/[&<>"']/g, function (character) {
      return {
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;"
      }[character];
    });
  }

  function renderTranscript() {
    var container = document.getElementById("transcript");
    var groups = [];
    var current = null;

    transcript.forEach(function (entry) {
      if (!current || current.name !== entry[0]) {
        current = { name: entry[0], rows: [] };
        groups.push(current);
      }
      current.rows.push({ time: entry[1], text: entry[2] });
    });

    container.innerHTML = groups.map(function (group) {
      return '<details class="script-group" open>' +
        '<summary>' + escapeHtml(group.name) + ' · ' + group.rows.length + ' 句</summary>' +
        '<div class="script-lines">' +
        group.rows.map(function (row) {
          return '<div class="script-line"><time>' + escapeHtml(row.time) + '</time><p>' + escapeHtml(row.text) + '</p></div>';
        }).join("") +
        '</div></details>';
    }).join("");
  }

  function bindWordLinks() {
    document.querySelectorAll(".word-nav a[href^='#word-']").forEach(function (link) {
      link.addEventListener("click", function () {
        var target = document.querySelector(link.getAttribute("href"));
        if (!target) return;
        target.classList.remove("flash");
        void target.offsetWidth;
        target.classList.add("flash");
      });
    });
  }

